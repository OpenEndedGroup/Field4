#!/usr/bin/env python3
r"""Check every in-page `](#slug)` link against the headings of the page it sits on.

Why this exists: on 2026-09-14 `faust.md:222` was found linking to
`#a-steal-clicks-and-by-how-much`, an anchor generated by a heading the first voice-pass firing had
renamed a day earlier. No guard in the repository covers an intra-page anchor -- `citationGates`
checks `file.kt:NNN` citations, `checkCodebaseReference` checks generated `**Used in:**` link texts,
and neither looks at `](#...)`. So a voice pass, whose whole job is renaming headings, is exactly
the thing most likely to break one and least likely to notice.

Cross-page anchors (`other_page.md#slug`) are checked too, when the target is a local page.

Slug generation mirrors python-markdown's `toc` extension, which is what Zensical renders with:

    value = re.sub(r'[^\w\s-]', '', value).strip().lower()
    value = re.sub(r'[-\s]+', '-', value)

Duplicate headings get `-1`, `-2`, ... suffixes, in document order, and those are accepted.

Usage:
    python3 check_anchors.py public/docs          # every page
    python3 check_anchors.py public/docs/faust.md # one page
"""

import pathlib
import re
import sys
import unicodedata

# ``` fences and ~~~ fences. A `#` inside a fence is code, not a heading.
FENCE = re.compile(r"^\s*(```|~~~)")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
# Markdown link targets: `](#slug)` and `](page.md#slug)`. Bare `<a name>` anchors are also
# honoured as definitions, since a few pages plant them by hand.
LINK = re.compile(r"\]\(([^)\s]*)#([^)\s]+)\)")
EXPLICIT_ANCHOR = re.compile(r"""<a\s+(?:name|id)=["']([^"']+)["']""")
# Attribute lists: `## Heading {#custom-slug}` overrides the derived slug. The generated
# `reference/` pages write these as `## pf.kt { #pf-kt }`, with spaces inside the braces, and
# python-markdown's attr_list accepts that -- so the inner `\s*` is load-bearing. Requiring `{#`
# adjacently made this script report 1915 of 2017 anchors dead on its first run.
ATTR_ID = re.compile(r"\{\s*#([^}\s]+)[^}]*\}\s*$")


def slugify(text, separator="-"):
    """python-markdown's `toc` slugify, including its unicode normalisation."""
    text = unicodedata.normalize("NFKD", text)
    text = text.encode("ascii", "ignore").decode("ascii")
    text = re.sub(r"[^\w\s-]", "", text).strip().lower()
    return re.sub(r"[%s\s]+" % re.escape(separator), separator, text)


def strip_inline(text):
    """Headings render their markdown before slugging: `` `code` ``, **bold**, [links](x)."""
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)   # links keep their text
    text = text.replace("`", "")
    text = re.sub(r"[*_]{1,3}(?=\S)(.+?)(?<=\S)[*_]{1,3}", r"\1", text)
    return text


def anchors_of(path):
    """Every slug a reader can reach on this page, in document order."""
    seen, out = {}, set()
    in_fence = False
    for ln in path.read_text(encoding="utf-8", errors="replace").split("\n"):
        if FENCE.match(ln):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        for explicit in EXPLICIT_ANCHOR.findall(ln):
            out.add(explicit)
        m = HEADING.match(ln)
        if not m:
            continue
        body = m.group(2)
        attr = ATTR_ID.search(body)
        if attr:
            out.add(attr.group(1))
            continue
        slug = slugify(strip_inline(body))
        if not slug:
            continue
        n = seen.get(slug, 0)
        seen[slug] = n + 1
        out.add(slug if n == 0 else "%s-%d" % (slug, n))
    return out


def links_of(path):
    """Every `](target#slug)` on the page, as (lineno, target, slug)."""
    out = []
    in_fence = False
    for i, ln in enumerate(path.read_text(encoding="utf-8", errors="replace").split("\n"), 1):
        if FENCE.match(ln):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        for target, slug in LINK.findall(ln):
            out.append((i, target, slug))
    return out


def main(argv):
    if len(argv) != 2:
        print(__doc__)
        return 2
    root = pathlib.Path(argv[1])
    pages = sorted(root.rglob("*.md")) if root.is_dir() else [root]
    base = root if root.is_dir() else root.parent

    cache = {}

    def anchors_for(p):
        if p not in cache:
            cache[p] = anchors_of(p) if p.exists() else None
        return cache[p]

    dead, checked = [], 0
    for page in pages:
        for lineno, target, slug in links_of(page):
            if target == "":
                where, label = page, "this page"
            elif target.endswith(".md"):
                where, label = (page.parent / target).resolve(), target
            else:
                continue   # an external URL with a fragment; not ours to check
            found = anchors_for(where)
            if found is None:
                dead.append((page, lineno, "%s does not exist" % label, slug))
                continue
            checked += 1
            if slug not in found:
                dead.append((page, lineno, label, slug))

    for page, lineno, label, slug in dead:
        print("%s:%d  dead anchor #%s in %s" % (page, lineno, slug, label))
    print("\n%d anchor link(s) checked across %d page(s), %d dead"
          % (checked, len(pages), len(dead)))
    try:
        rel = base.resolve()
    except OSError:
        rel = base
    if not dead:
        print("every in-page and cross-page anchor under %s resolves" % rel)
    return 1 if dead else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
