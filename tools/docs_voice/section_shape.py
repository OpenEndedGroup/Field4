#!/usr/bin/env python3
"""Rank pages by STRUCTURE, not by wording — the two routes the twenty-seventh firing
(2026-09-18) found six pages with and recommended adding to the routine.

`score_voice.py` scores sentences and headings. It cannot see a page whose API is buried
under the verification of the API, because every sentence in the verification is fine.
These two filters see exactly that:

  verification mass   the fraction of a page's words sitting under a `##` whose heading
                      names measurement, checking, agreement, provenance or proof.
  tail verification   whether the LAST or second-last `##` names verification — a page
                      that ends on how it checks itself rather than on what to do next.

Both are targeting tools. A high fraction is not a fault: `tetgen.md`'s 17 data tables
ARE the deliverable, and a measurement page is allowed to be about measurement. Read the
page. What you are looking for is a page whose SUBJECT is an API and whose MASS is proof.

## RETIRE THIS FILE. Both structural columns are 0 true, audited hit by hit 2026-09-22

The ledger has carried "section_shape.py to retire" since the forty-fifth firing, on the
strength of its *harness-density* column having no unactioned rows left. The forty-ninth
audited the other two columns, which nobody had, and they are worse than empty:

**Verification mass: 0 true out of 26 pages.** Every hit is a content heading, and five
of them were read in full before that was believed. The regex is the problem in four
separable ways, and none of the four is fixable by narrowing it:

- `check\w*` matches **`Checkerboard`**. `fabricate_renderer.md` scores 9.2% on
  `## Shiny Torii on Checkerboard Planes` and `## Shader-Generated Checkerboard`. Same
  family as `grep -i TODO` matching `toDouble`: a verification word is also a substring.
- `measur\w*` is the single biggest source — 10 of the 26 — and in documentation it is
  overwhelmingly **a verb the reader performs with the API**, which is the exact opposite
  of "here is how I know". `## Measuring a solid` (manifold), `## Measuring and querying`
  (mesh), `## The two quality measures` (tetgen), `## Height is measured from the content
  edge` (output_panel_sizing), `## Extrapolation is measured in hull-crossings`.
- `check`/`test` also match **instructions to the reader**: `## Headset check`,
  `## Checking it on your own machine`, `## Testing the head`. A page telling you to go
  and check something is the most user-facing shape there is.
- `guard`, `provenance`, `convergence`, `agree` match **product features**: `## The
  autosave guard`, `## Defence 4 — the WebSocket upgrade guard`, `## Guards: \`where { }\``
  (a DSL keyword), `## Provenance: every output element remembers where it came from`,
  `## Convergence and the termination cap`, `## Dot product: "how much do these agree?"`.

**Tail verification: 0 true out of 5.** Four are the same false positives; the fifth,
`building_and_testing.md`'s `## Running the tests`, is on the page whose subject is
running the tests.

**It also scores generated pages, alone among the analysers in this directory.** Its
`collect()` below is the only one that does not go through `score_voice.is_generated()`,
excluding `reference/` and `linear_algebra_api.md` by hardcoded path instead — so
`field_audio_service_reference.md` ("Generated by scripts/generate-docs.py; do not edit")
is ranked, and its `## Verification lanes` is one of the five tail rows above. Any new
analyser must reuse `score_voice.collect()`; that is the whole reason it is shared.

Not deleted in the forty-ninth firing only because the README line it appears on
("Thirteen read-only analysers") is being rewritten on the unlanded `docs/voice-2026-09-22e`,
and two branches editing one count word conflict. Delete the file and its README row
together, after that branch lands.

Usage:
    section_shape.py public/docs [--assets] [--min-words N] [--top N]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# Words that make a heading a verification heading. Kept deliberately narrow: these are
# the ones that mean "here is how I know", not the ones that mean "here is a number".
# `performance`/`cost`/`budget` NO — a reader acts on those.
#
# `measur\w*` was here until 2026-09-24 and was the single biggest source of noise on this
# board. Censused hit by hit over every `##`-`######` heading in public/docs: **12 of 13
# were false**, because in this tree "measure" overwhelmingly names the *subject* rather
# than the checking of it. `manifold.md` "Measuring a solid", `mesh_examples.md`
# "Measuring and querying", `three_output.md` "Measuring and sectioning a solid" and
# `fline_examples.md` "Measuring" are API sections; `output_panel_sizing.md` "Height is
# measured from the content edge" and "Why the fallback measures outwards" are mechanism;
# `keyframe_autosweep.md` "Extrapolation is measured in hull-crossings" is a units idiom;
# `audio_ai_corpus_microscope.md` "What each window is measured by", `tetgen.md` "The two
# quality measures" and `statistics_examples.md` "Measuring the null yourself" are the
# page's own topic. The one true hit, `chain_polytope_render.md` "The same surface,
# measured by two implementations that share no code", is still caught -- by
# `share\s+no\s+code`, which is the part of it that actually means cross-verification.
#
# The cost of the false positives was not just noise in a column. On 2026-09-24 the board
# ranked `output_panel_sizing` at 24.1% and `audio_ai_corpus_microscope` at 29.8% and sent
# a firing to read both; both are excellent pages and neither had a verification section at
# all. Meanwhile `keyframe_autosweep.md`'s real one, `## Where it is exercised`, scored
# nothing -- see `exercis\w*` below.
VERIFY_WORDS = re.compile(
    r"\b("
    r"verif\w*|check\w*|checked|cross-check\w*|agree\w*|agreement"
    # `exercis\w*`: "Where it is exercised" is this tree's idiom for "which suites cover
    # this", and the board could not see it. Added 2026-09-24 with exactly one recorded
    # instance (`keyframe_autosweep.md:423`, disposed of the same night to
    # `dev_docs/KEYFRAME_SWEEP_AGREEMENT.md`), so it currently matches NOTHING. That is
    # intended: it is here for the next one, not to score a backlog.
    r"|exercis\w*"
    # `regression suite`, not bare `regression`: this tree documents statistics, and
    # `statistics_examples.md` is one page away from a heading about fitting a regression.
    # Censused 2026-09-24 -- one heading in public/docs contains `regression`
    # (`output_panel_sizing.md:295`) and it is a true hit; bare `pin`/`pinned` is 1 true of
    # 3 (`dataframe.md` "the version pin", `three_output.md` "The pinned console"), so the
    # suite is what is matched and the verb is not.
    r"|regression\s+suite"
    r"|provenance|proof|proven|prove[sd]?|assert\w*|guard\w*|guarantee[sd]?"
    # NOT bare `reproduc\w*`: "Reproduction with modification" is this tree's standard
    # heading for "here is the code behind the figure, go edit it" — a teaching section,
    # and it put rectsl_examples.md's 1589-word gallery at 29% on the first run.
    # Only the non-determinism sense counts.
    r"|evidence|corrobor\w*|reproducib\w*|residual\w*|census|censuses"
    r"|convergence|accuracy|error\s+table|how\s+(we|i|this|the\s+page)\s+know"
    r"|taken\s+on\s+trust|on\s+trust|independently\s+known|share\s+no\s+code"
    r"|test(s|ed|ing)?|validat\w*|calibrat\w*"
    r")\b",
    re.I,
)

FENCE = re.compile(r"^\s*(```|~~~)")
COMMENT_OPEN = re.compile(r"<!--")
COMMENT_CLOSE = re.compile(r"-->")


def sections(text: str):
    """Yield (heading, word_count) per `##`-level section, fences and HTML comments
    excluded from the word count. Front matter above the first `##` is heading None."""
    out = []
    heading = None
    words = 0
    in_fence = False
    in_comment = False
    for line in text.splitlines():
        # Comments first: one of them contains a ``` line, which is how the first
        # firing's fence tracker got confused.
        if in_comment:
            if COMMENT_CLOSE.search(line):
                in_comment = False
            continue
        if COMMENT_OPEN.search(line) and not COMMENT_CLOSE.search(line):
            in_comment = True
            continue
        if FENCE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        m = re.match(r"^##\s+(.*?)\s*$", line)
        if m:
            out.append((heading, words))
            heading = m.group(1)
            words = 0
            continue
        words += len(line.split())
    out.append((heading, words))
    return out


# The body-text half of what VERIFY_WORDS sees in headings: a section whose PROSE is dense in
# harness identifiers is telling a reader what the tests are called, which is an inventory nobody
# can act on. Folded in 2026-09-19 at the twenty-eighth firing's request — it found
# `morpho_examples.md`'s step 6 (6 identifiers in 116 words, 51.7/1k) on a page every other route
# scored 0. Deliberately NOT `\w*Test` bare: `TestKit`, `TestDouble` and the like are API a reader
# uses. The suffix form only, plus the two build words.
HARNESS_IDENT = re.compile(
    r"\b(?:[A-Z]\w*(?:Test|Guard|Contract)|gradlew|jvmTest|commonTest|assert[A-Z]\w*|"
    r"assertThat|assertEquals|assertTrue|assertFalse)\b"
)


def harness_sections(text: str, min_words: int = 60):
    """Yield (heading, words, identifier_count) per `##`/`###` section, fences and HTML
    comments excluded — the same exclusions `sections()` makes, for the same reasons.

    Collapsed `??? aside` bodies are excluded too, on the same grounds the scorer counts only
    `!!!`: a collapsed aside costs a reader nothing. Measured when this route was folded in —
    `fieldml_host_bridge.md`'s "Where to look" led the board at 41.4/1k and every one of its
    seven identifiers was inside `??? aside "Which test holds which claim"`, which is exactly
    where an inventory of test classes is supposed to live.
    """
    out = []
    heading, body, in_fence, in_comment = None, [], False, False
    aside_indent = None

    def flush():
        joined = " ".join(body)
        n = len(joined.split())
        if heading and n >= min_words:
            out.append((heading, n, len(HARNESS_IDENT.findall(joined))))

    for line in text.splitlines():
        if in_comment:
            if COMMENT_CLOSE.search(line):
                in_comment = False
            continue
        if COMMENT_OPEN.search(line) and not COMMENT_CLOSE.search(line):
            in_comment = True
            continue
        if FENCE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        if aside_indent is not None:
            if not line.strip():
                continue
            if len(line) - len(line.lstrip()) > aside_indent:
                continue
            aside_indent = None
        if re.match(r"^\s*\?\?\?", line):
            aside_indent = len(line) - len(line.lstrip())
            continue
        m = re.match(r"^#{2,3}\s+(.*?)\s*$", line)
        if m:
            flush()
            heading, body = m.group(1), []
            continue
        body.append(line)
    flush()
    return out


def collect(root: Path, assets: bool):
    for p in sorted(root.rglob("*.md")):
        rel = p.relative_to(root.parent.parent) if root.is_absolute() else p
        s = str(p)
        is_asset = "/assets/" in s
        if is_asset != assets:
            continue
        if "/reference/" in s or s.endswith("linear_algebra_api.md"):
            continue
        yield p


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--assets", action="store_true")
    ap.add_argument("--min-words", type=int, default=400)
    ap.add_argument("--top", type=int, default=25)
    a = ap.parse_args()

    rows = []
    tail = []
    dense = []
    for p in collect(Path(a.root), a.assets):
        text = p.read_text(encoding="utf-8", errors="replace")
        for h, n, k in harness_sections(text):
            if k >= 3:
                dense.append((k * 1000.0 / n, k, n, p, h))
        secs = sections(text)
        total = sum(w for _, w in secs)
        if total < a.min_words:
            continue
        vmass = sum(w for h, w in secs if h and VERIFY_WORDS.search(h))
        heads = [h for h, _ in secs if h]
        if heads:
            last_two = heads[-2:]
            hit = [h for h in last_two if VERIFY_WORDS.search(h)]
            if hit:
                tail.append((len(heads) - len(last_two) + last_two.index(hit[0]) + 1,
                             len(heads), p, hit[0]))
        rows.append((vmass / total if total else 0.0, vmass, total, p))

    rows.sort(reverse=True)
    print("verification MASS by section — fraction of the page's words under a "
          "verification `##`\n")
    print(f"{'frac':>6}  {'v-words':>7}  {'words':>6}  path")
    for frac, vmass, total, p in rows[: a.top]:
        if frac <= 0:
            break
        print(f"{frac*100:5.1f}%  {vmass:7d}  {total:6d}  {p}")

    print("\n\nTAIL verification — the page's LAST or second-last `##` names verification\n")
    for idx, n, p, h in sorted(tail, key=lambda r: -r[1]):
        print(f"  {p}   (`##` {idx}/{n}) {h!r}")
    dense.sort(reverse=True)
    print("\n\nHARNESS-IDENTIFIER DENSITY — `##`/`###` sections whose PROSE names test classes,\n"
          "guards and build tasks. Per 1000 words, 3 identifiers minimum.\n")
    print(f"{'per1k':>6}  {'n':>3}  {'words':>5}  page / section")
    for per1k, k, n, p, h in dense[: a.top]:
        print(f"{per1k:6.1f}  {k:3d}  {n:5d}  {p}\n{'':>17}{h!r}")

    print(f"\n{len(rows)} pages over {a.min_words} words; {len(tail)} end on verification; "
          f"{len(dense)} section(s) over the harness-density floor.")
    return 0


def live_fire():
    """Pin the 2026-09-24 `measur\\w*` census in both directions.

    The narrowing that made this board usable is also the shape most easily
    over-applied, so each case below pins a false positive *staying* dead AND the true
    sense staying reachable. Every must-not-fire string is a real heading from
    `public/docs` on that date, quoted with its page.
    """
    must_not_fire = [
        "## Measuring a solid",                                   # manifold.md:30, API
        "## Measuring and querying",                              # mesh_examples.md:463
        "## Measuring and sectioning a solid",                    # three_output.md:389
        "#### Measuring",                                         # fline_examples.md:252
        "## Height is measured from the content edge",            # output_panel_sizing.md:210
        "## Why the fallback measures outwards",                  # output_panel_sizing.md:131
        "## Extrapolation is measured in hull-crossings",         # keyframe_autosweep.md:303
        "## What each window is measured by",                     # audio_ai_corpus_microscope.md:10
        "## The two quality measures",                            # tetgen.md:126
        "## Measuring the null yourself",                         # statistics_examples.md:313
        "## One mesh to measure, another to draw",                # chain_polytope_render.md:193
        "## Example: recovering an unmeasured velocity",          # state_estimation_examples.md:196
    ]
    must_fire = [
        # The one true hit in that census. It survives `measur\w*`'s removal because the
        # part of it that means cross-verification is `share no code`, which is its own
        # alternative -- delete that and this case goes red, which is the point.
        "#### The same surface, measured by two implementations that share no code",
        "## Where it is exercised",          # keyframe_autosweep.md:423, the idiom the board could not see
        "## Running the tests",              # building_and_testing.md:171
        "## Verification lanes",             # field_audio_service_reference.md
        "## Testing the head",               # ar_reference.md:160
        "## What the regression suite pins",  # output_panel_sizing.md:295
    ]
    bad = 0
    for h in must_not_fire:
        if VERIFY_WORDS.search(h):
            print(f"live-fire FAIL: should be silent, fired: {h!r}")
            bad += 1
    for h in must_fire:
        if not VERIFY_WORDS.search(h):
            print(f"live-fire FAIL: should fire, silent: {h!r}")
            bad += 1
    if not bad:
        print(f"live fire OK: {len(must_fire)} must-fire, {len(must_not_fire)} must-not-fire, "
              "all correct")
    return 1 if bad else 0


if __name__ == "__main__":
    if "--live-fire" in sys.argv:
        sys.exit(live_fire())
    sys.exit(main())
