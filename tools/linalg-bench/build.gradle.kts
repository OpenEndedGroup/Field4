plugins {
    kotlin("jvm")
    id("me.champeau.jmh") version "0.7.2"
}

repositories {
    mavenCentral()
}

dependencies {
    // JOML is a benchmark-only baseline. It is NOT a Field runtime dependency — it stays removed
    // from the app. This lets us verify the "generated heap Vector3f ≈ JOML Vector3f" assumption
    // that the whole ditch-JOML decision rests on.
    "jmhImplementation"("org.joml:joml:1.10.7")
}

// The arena safety profile is a compile-time constant, exactly as in the main build. Run the
// suite once per value to compare compiled-in against compiled-out arena validation:
//   ./gradlew :tools:linalg-bench:jmh                           (checks compiled in, default)
//   ./gradlew :tools:linalg-bench:jmh -PlinalgArenaChecks=false (checks compiled out)
val linalgArenaChecks = providers.gradleProperty("linalgArenaChecks")
    .map { value ->
        value.toBooleanStrictOrNull()
            ?: error("-PlinalgArenaChecks must be true or false, got '$value'")
    }
    .orElse(true)

val profileDir = layout.buildDirectory.dir("generated/linalg-profile/kotlin")
val generateLinalgBuildProfile = tasks.register("generateLinalgBuildProfile") {
    group = "code generation"
    description = "Generates the compile-time arena safety flag for the benchmark build."
    inputs.property("arenaChecks", linalgArenaChecks)
    outputs.dir(profileDir)
    doLast {
        val output = profileDir.get().file("afield/stdlib/linalg/arena/ArenaBuildProfile.kt").asFile
        output.parentFile.mkdirs()
        output.writeText(
            """
            // Generated by generateLinalgBuildProfile. Do not edit.
            package afield.stdlib.linalg.arena

            internal const val ARENA_CHECKS_COMPILED: Boolean = ${linalgArenaChecks.get()}
            """.trimIndent() + "\n"
        )
    }
}

// The linear-algebra sources are dependency-free (Kotlin stdlib + JDK FFM only), so the benchmark
// compiles them directly instead of dragging in the whole afield runtime. This keeps the build fast
// and lets the arena-checks profile be set independently of the main build.
val assembleLinalgSources = tasks.register<Copy>("assembleLinalgSources") {
    val root = rootProject.layout.projectDirectory
    into(layout.buildDirectory.dir("linalg-sources"))
    from(root.dir("src/generatedLinalg/kotlin")) { include("afield/stdlib/linalg/**") }
    from(root.dir("src/jvmMain/kotlin")) { include("afield/stdlib/linalg/**") }
    // Vector8h stores binary16 directly, so the generated Vectors.kt imports
    // afield.four.util.floatToHalfBits/halfBitsToFloat. That is the ONLY thing the generated sources
    // need from outside afield.stdlib.linalg, and 16bits.kt in turn needs nothing but Vector2f/3f/4f,
    // which are already here — so copying it keeps the "no afield runtime" property intact. Without
    // it :tools:linalg-bench does not compile at all (it had been failing since Vector8h landed).
    from(root.dir("src/jvmMain/kotlin")) { include("afield/four/util/16bits.kt") }
}

kotlin {
    sourceSets.named("main") {
        kotlin.srcDir(assembleLinalgSources)
        kotlin.srcDir(generateLinalgBuildProfile)
    }
}

// Must be the SAME JVM the app runs on (the root build pins GRAAL_VM), or the numbers describe a JVM
// nobody ships. It also matters mechanically, and silently: -XX:+EnableJVMCI below is a supported
// option on GraalVM but an *experimental* one everywhere else, so a plain `jvmToolchain(25)`
// resolves to Adoptium and every forked JMH JVM dies with "must be enabled via
// -XX:+UnlockExperimentalVMOptions" while Gradle still reports BUILD SUCCESSFUL over an empty
// results table. :tools:imaging-bench hit exactly this. A benchmark that reports nothing must not
// look like a benchmark that passed.
java {
    toolchain {
        languageVersion.set(JavaLanguageVersion.of(25))
        vendor.set(JvmVendorSpec.GRAAL_VM)
    }
}

// The generated collection-literal constructors (`val v: Vector3f = [1, 2, 3]`) use the same
// experimental feature the main afield build enables.
tasks.withType<org.jetbrains.kotlin.gradle.tasks.KotlinCompile>().configureEach {
    compilerOptions.freeCompilerArgs.add("-Xcollection-literals")
}

// Same gradle-property overrides as :tools:imaging-bench, so you can measure one arm without the
// whole suite:
//   ./gradlew :tools:linalg-bench:jmh -Pjmh.includes='.*Spline.*' -Pjmh.fork=1 -Pjmh.iterations=3
//
// `jmh.includes` is ONE regex, not a list. The plugin flattens its `includes` list into a single
// comma-joined argument, so passing two patterns yields a regex containing a literal comma, which
// matches nothing and reports "No matching benchmarks" — measured, not assumed. Select several arms
// with alternation instead: '.*(heapFloatReusedDestinations|jomlReusedDestinations).*'.
fun jmhProperty(name: String): String? = providers.gradleProperty("jmh.$name").orNull

jmh {
    warmupIterations.set(jmhProperty("warmupIterations")?.toInt() ?: 4)
    warmup.set("1s")
    iterations.set(jmhProperty("iterations")?.toInt() ?: 5)
    timeOnIteration.set("1s")
    fork.set(jmhProperty("fork")?.toInt() ?: 2)
    jmhProperty("includes")?.let { includes.set(listOf(it)) }
    benchmarkMode.set(listOf("avgt"))
    timeUnit.set("ns")
    resultFormat.set("TEXT")
    // The bulk/SIMD kernels under afield.stdlib.linalg.bulk use jdk.incubator.vector, same as the
    // main build's runJvm/Test tasks; the forked JMH JVMs need the same opt-in. On the GraalVM
    // toolchain we must also force C2 as the host JIT (-XX:-UseJVMCICompiler, JVMCI still enabled for
    // Truffle) or the Vector API / scalar loops don't vectorize and the numbers are meaningless — see
    // the vectorizationJvmArgs note in the root build.gradle.kts.
    jvmArgsAppend.set(listOf("--add-modules", "jdk.incubator.vector", "-XX:+EnableJVMCI", "-XX:-UseJVMCICompiler"))
    // To reproduce the allocation story, temporarily add e.g.
    //   includes.set(listOf("Spline")); profilers.set(listOf("gc"))
    // gc.alloc.rate.norm then reports bytes/op — ~0 for arena and segment backends.
}
