"""Shortcuts on the docs pages are written as keycaps, `++cmd+shift+p++`, in one spelling.

`pymdownx.keys` (configured in `public/zensical.yml`) draws them; `cmd` is Field's cmd, Command on
macOS and Control elsewhere, and its cap reads ⌘/⌃. Before this check the pages spelled one
shortcut a dozen ways (`cmd+p`, `Alt-Enter`, **ctrl/command-4**, alt/option-click, Cmd/Ctrl+D,
hand-written <kbd>s). This fails on any of those in prose, outside fences.

Not checked: `keybindings.md`, whose `cmd+shift+d` specs are what you type into
`keybindings.yaml` and stay code; generated pages (`reference/`, transcript assets, pages headed
"DO NOT EDIT"/"generated by"), whose source is elsewhere; image alt text and raw HTML lines.
"""
from __future__ import annotations

import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "public/docs"
SKIP_PAGES = {"keybindings.md"}
# Sources of captured web publications (tools/docs_publications.py digests the page), so an edit
# means recapturing those documents in Field. Convert them when they are next recaptured.
PUBLICATION_SOURCES = {"agent_transcripts.md", "field_vr_ide.md"}
SKIP_DIRS = ("reference/", "assets/")
GENERATED = re.compile(r"DO NOT EDIT|generated by", re.I)

MOD = r"(?:cmd|command|ctrl|control|alt|option|opt|shift|meta|⌘|⌥|⇧)"
MODALT = rf"{MOD}(?:/{MOD})?"
KEY = (r"(?:f\d{1,2}|space|enter|return|esc|escape|tab|backspace|delete|del|up|down|left|right"
       r"|home|end|pageup|pagedown|[↑↓←→]|[a-z0-9](?![\w])|[\[\],./\\;=`']"
       r"|double-click|click|drag|scroll|wheel)")
CHORD = rf"{MODALT}(?:\s*[-+]\s*{MODALT})*\s*[-+]\s*{KEY}"
CODE_CHORD = re.compile(rf"`\s*{CHORD}(?:\s+{CHORD})?\s*`", re.I)
BARE_CHORD = re.compile(rf"(?<![\w`/.+-]){CHORD}", re.I)
RAW_KBD = re.compile(r"<kbd\b", re.I)
# Spans that are not prose: images (alt text cannot hold markup), tags, link targets, code, keycaps.
NOT_PROSE = re.compile(r"!\[[^\]]*\]\([^)]*\)|<[^>\n]+>|\]\([^)]*\)|`[^`\n]+`|\+\+[^+\s]\S*?\+\+")


def offending(text: str) -> list[tuple[int, str]]:
    """(line, spelling) for every shortcut not written as a keycap, outside fences."""
    found = []
    fence = None
    for n, line in enumerate(text.splitlines(), 1):
        s = line.lstrip()
        m = re.match(r"(`{3,}|~{3,})", s)
        if m:
            fence = m.group(1) if fence is None else (None if s.startswith(fence) else fence)
            continue
        if fence:
            continue
        for k in RAW_KBD.finditer(line):
            found.append((n, line[k.start():k.start() + 24]))
        if s.startswith("<") or s.startswith("#"):
            continue
        found += [(n, c.group(0)) for c in CODE_CHORD.finditer(line)]
        prose = NOT_PROSE.sub(lambda c: " " * len(c.group(0)), line)
        found += [(n, b.group(0)) for b in BARE_CHORD.finditer(prose)]
    return found


def pages() -> list[Path]:
    out = []
    for path in sorted(DOCS.rglob("*.md")):
        rel = path.relative_to(DOCS).as_posix()
        if rel in SKIP_PAGES or rel in PUBLICATION_SOURCES or rel.startswith(SKIP_DIRS):
            continue
        if GENERATED.search(path.read_text(errors="replace")[:400]):
            continue
        out.append(path)
    return out


class DocsKeycapsTest(unittest.TestCase):
    def test_spellings_are_caught(self):
        for text in ["press `cmd+p`", "press `alt/option-Enter`", "**ctrl/command-4** opens",
                     "alt/option-click a box", "| Cmd/Ctrl+D |", "Shift-click it", "<kbd>⌘</kbd>",
                     "`Ctrl+Shift+A`", "press Alt+1", "`alt-[` solos"]:
            with self.subTest(text=text):
                self.assertTrue(offending(text), text)

    def test_keycaps_code_and_fences_pass(self):
        for text in ["press ++cmd+p++", "++alt++-click a box", "the command `new-box`",
                     "```yaml\nnew-box: \"cmd+alt+b\"\n```", "![Opt-0 runs it](a.png)",
                     "the command-line and option-value", "alt-row and shift-register", "`--option-name`"]:
            with self.subTest(text=text):
                self.assertEqual(offending(text), [], text)

    def test_pages_write_shortcuts_as_keycaps(self):
        problems = []
        for path in pages():
            for n, spelling in offending(path.read_text(errors="replace")):
                problems.append(f"{path.relative_to(ROOT)}:{n}: {spelling.strip()}")
        self.assertEqual(problems, [], "\nWrite a shortcut as a keycap: `cmd+shift+p` -> ++cmd+shift+p++, "
                         "alt/option-click -> ++alt++-click, ctrl-space (the Control key itself) -> "
                         "++ctrl+space++, `alt-[` -> ++alt+bracket-left++, `cmd+/` -> ++cmd+slash++.\n"
                         + "\n".join(problems))


if __name__ == "__main__":
    unittest.main()
