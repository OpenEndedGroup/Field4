#!/usr/bin/env python3
"""Turn JMH output from :tools:imaging-bench into the performance table in the docs.

The imaging family's whole claim is a performance claim, so the numbers on the page have to be
numbers someone actually measured — and they have to stay that way while the code gets faster. A
hand-copied table is stale the first time anyone optimises `pyrDown`. So:

    ./gradlew :tools:imaging-bench:jmh                       # measure
    python3 tools/imaging_bench_doc.py --results <file> --write   # publish
    python3 tools/imaging_bench_doc.py --check               # CI / pre-commit

`--write` replaces everything between the BEGIN/END markers in the docs page from the committed
results file. `--check` regenerates into memory and diffs, exiting non-zero if the page has drifted
— the same shape as `checkCodebaseReference`.

The committed results file is the evidence. If you change the numbers on the page without changing
that file, --check fails, which is the point.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RESULTS = REPO / "tools" / "imaging-bench" / "results-1920x1080.txt"
DOC = REPO / "public" / "docs" / "imaging_examples.md"

BEGIN = "<!-- BEGIN imaging-bench table — generated by tools/imaging_bench_doc.py, do not edit -->"
END = "<!-- END imaging-bench table -->"

# Benchmark method name -> (row label, which arm). Anything not listed is ignored, so adding an
# arm to the JMH class does not silently change the published table.
ARMS: dict[str, tuple[str, str]] = {
    "scalarOursGaussianGray": ("Gaussian blur, sigma 2, gray", "scalar"),
    "oursGaussianGray": ("Gaussian blur, sigma 2, gray", "ours"),
    "opencvGaussianGray": ("Gaussian blur, sigma 2, gray", "opencv"),
    "scalarOursGaussianRgb": ("Gaussian blur, sigma 2, RGB", "scalar"),
    "oursGaussianRgb": ("Gaussian blur, sigma 2, RGB", "ours"),
    "opencvGaussianRgb": ("Gaussian blur, sigma 2, RGB", "opencv"),
    "scalarOursSobel": ("Sobel", "scalar"),
    "oursSobel": ("Sobel", "ours"),
    "opencvSobel": ("Sobel", "opencv"),
    "oursScharr": ("Scharr", "ours"),
    "opencvScharr": ("Scharr", "opencv"),
    "oursLaplacian": ("Laplacian", "ours"),
    "opencvLaplacian": ("Laplacian", "opencv"),
    "oursConvolve2D": ("Dense 9x9 convolution", "ours"),
    "opencvFilter2D": ("Dense 9x9 convolution", "opencv"),
    "oursLuma": ("Luma (RGB to gray)", "ours"),
    "opencvLuma": ("Luma (RGB to gray)", "opencv"),
    "oursBoxBlur": ("Box blur, radius 2", "ours"),
    "opencvBoxBlur": ("Box blur, radius 2", "opencv"),
    "oursMedian": ("Median, radius 2", "ours"),
    "opencvMedian": ("Median, radius 2", "opencv"),
    "oursResizeDown": ("Resize to half", "ours"),
    "opencvResizeDown": ("Resize to half", "opencv"),
    "oursBilateral": ("Bilateral", "ours"),
    "opencvBilateral": ("Bilateral", "opencv"),
    "oursPyrDown": ("pyrDown", "ours"),
    "opencvPyrDown": ("pyrDown", "opencv"),
}

# Row order on the page: fastest-relative-to-OpenCV first is tempting, but a stable, meaningful
# order is better for a page people re-read as the numbers change.
ORDER = [
    "Gaussian blur, sigma 2, gray",
    "Gaussian blur, sigma 2, RGB",
    "Sobel",
    "Scharr",
    "Laplacian",
    "Dense 9x9 convolution",
    "Luma (RGB to gray)",
    "Box blur, radius 2",
    "Median, radius 2",
    "Resize to half",
    "Bilateral",
    "pyrDown",
]

ROW_RE = re.compile(
    r"^ImagingBenchmark\.(\w+)\s+avgt\s+(\d+)\s+([\d.]+)\s+±\s+([\d.]+)\s+(\S+)\s*$"
)


def parse(results_text: str) -> dict[str, dict[str, tuple[float, float]]]:
    """method-label -> arm -> (score_ms, error_ms)."""
    table: dict[str, dict[str, tuple[float, float]]] = {}
    seen_any = False
    for line in results_text.splitlines():
        m = ROW_RE.match(line.strip())
        if not m:
            continue
        seen_any = True
        method, _cnt, score, err, unit = m.groups()
        if unit != "ms/op":
            raise SystemExit(f"expected ms/op, got {unit!r} for {method} — check the JMH config")
        if method not in ARMS:
            continue
        label, arm = ARMS[method]
        table.setdefault(label, {})[arm] = (float(score), float(err))
    if not seen_any:
        raise SystemExit(
            "no JMH result rows found. A benchmark run that dies in @Setup still exits 0 and "
            "prints an empty table — check the log before trusting a green build."
        )
    return table


def fmt(v: float) -> str:
    return f"{v:.2f}" if v < 100 else f"{v:.0f}"


def render(table: dict[str, dict[str, tuple[float, float]]]) -> str:
    out = [
        BEGIN,
        "",
        "| operation | before (scalar) | now | OpenCV 4.9, 1 thread | now vs OpenCV |",
        "|---|---|---|---|---|",
    ]
    for label in ORDER:
        arms = table.get(label)
        if not arms or "ours" not in arms or "opencv" not in arms:
            continue
        ours, ours_e = arms["ours"]
        cv, cv_e = arms["opencv"]
        before = f"{fmt(arms['scalar'][0])} ± {fmt(arms['scalar'][1])}" if "scalar" in arms else "—"
        ratio = ours / cv if cv else float("nan")
        # Bold the wins, so the page cannot quietly present a loss as a win.
        ratio_cell = f"**{ratio:.2f}x**" if ratio < 1.0 else f"{ratio:.2f}x"
        out.append(
            f"| {label} | {before} | {fmt(ours)} ± {fmt(ours_e)} | "
            f"{fmt(cv)} ± {fmt(cv_e)} | {ratio_cell} |"
        )
    out += ["", END]
    return "\n".join(out)


def splice(doc_text: str, block: str) -> str:
    i, j = doc_text.find(BEGIN), doc_text.find(END)
    if i == -1 or j == -1:
        raise SystemExit(f"markers not found in {DOC.relative_to(REPO)} — add them first")
    return doc_text[:i] + block + doc_text[j + len(END):]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, default=RESULTS)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    if not args.results.exists():
        raise SystemExit(f"no results file at {args.results}; run ./gradlew :tools:imaging-bench:jmh")

    block = render(parse(args.results.read_text()))
    current = DOC.read_text()
    updated = splice(current, block)

    if args.write:
        DOC.write_text(updated)
        print(f"wrote the benchmark table into {DOC.relative_to(REPO)}")
        return 0
    if args.check:
        if updated != current:
            print(
                f"{DOC.relative_to(REPO)}: benchmark table is out of date with "
                f"{args.results.relative_to(REPO)}.\n"
                f"Regenerate: python3 tools/imaging_bench_doc.py --write",
                file=sys.stderr,
            )
            return 1
        print("imaging benchmark table is up to date")
        return 0
    print(block)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
