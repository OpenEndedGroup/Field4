package afield.stdlib.linalg.codegen

import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.LinkOption.NOFOLLOW_LINKS
import kotlin.io.path.createDirectories
import kotlin.io.path.exists
import kotlin.io.path.readText
import kotlin.io.path.writeText

private data class Arguments(val output: Path, val docsOutput: Path, val check: Boolean, val packages: Path?)

internal const val GENERATED_MARKER = "// DO NOT EDIT — generated by tools/linalg-generator"

internal fun generatedSources(packages: GenerationPackages, emitter: KotlinEmitter): Map<Path, String> = linkedMapOf(
    packages.sourcePath(packages.linalg, "Vectors.kt") to emitter.emitHeapVectors(),
    packages.sourcePath(packages.extensions, "Swizzles.kt") to emitter.emitSwizzles(),
    packages.sourcePath(packages.extensions, "VectorOperators.kt") to emitter.emitVectorOperators(),
    packages.sourcePath(packages.arena, "ArenaVectors.kt") to emitter.emitArenaVectors(),
    packages.sourcePath(packages.storage, "SegmentVectors.kt") to emitter.emitSegmentVectors(),
    packages.sourcePath(packages.bulk, "BulkVectors.kt") to emitter.emitBulkVectors(),
    packages.sourcePath(packages.linalg, "TransformSemantics.kt") to emitter.emitTransformSemantics(),
    packages.sourcePath(packages.linalg, "Transforms.kt") to generatedTemplate("Transforms.kt", packages),
    packages.sourcePath(packages.linalg, "CompatTypes.kt") to generatedTemplate("CompatTypes.kt", packages),
)

fun main(rawArguments: Array<String>) {
    val arguments = parseArguments(rawArguments)
    val packages = arguments.packages?.let { Files.newInputStream(it).use(GenerationPackages::read) } ?: GenerationPackages.default()
    val emitter = KotlinEmitter(FieldAlgebraModel.build(), packages = packages)
    val files = generatedSources(packages, emitter)
    val documentationFiles = linkedMapOf(
        Path.of("linear_algebra_api.md") to emitter.emitReferenceMarkdown(),
    )

    // A package move must not leave a second copy of the generated declarations behind.
    // Only recognized filenames carrying our ownership header are candidates for removal.
    val filenames = files.keys.map { it.fileName }.toSet()
    val obsolete = if (arguments.output.exists()) Files.walk(arguments.output).use { paths ->
        paths.filter { Files.isRegularFile(it, NOFOLLOW_LINKS) && it.fileName in filenames &&
            arguments.output.relativize(it) !in files &&
            Files.newBufferedReader(it).use { reader -> reader.readLine() == GENERATED_MARKER } }.toList()
    } else emptyList()
    val stale = (files.map { (relative, content) -> arguments.output.resolve(relative) to content } +
        documentationFiles.map { (relative, content) -> arguments.docsOutput.resolve(relative) to content })
        .mapNotNull { (target, content) ->
        if (arguments.check) {
            if (!target.exists() || target.readText() != content) target.toString() else null
        } else {
            target.parent.createDirectories()
            if (!target.exists() || target.readText() != content) {
                target.writeText(content)
                println("generated $target")
            }
            null
        }
    }
    if (!arguments.check) obsolete.forEach { Files.delete(it); println("removed obsolete generated source $it") }

    if (arguments.check && (stale.isNotEmpty() || obsolete.isNotEmpty())) {
        error(
            buildString {
                appendLine("Generated linear-algebra sources are stale:")
                stale.forEach { appendLine("  $it") }
                obsolete.forEach { appendLine("  obsolete generated source: $it") }
                append("Run ./gradlew generateLinalg")
            }
        )
    }
    if (arguments.check) println("generated linear-algebra sources are current")
}

private fun generatedTemplate(name: String, packages: GenerationPackages): String {
    val source = checkNotNull(object {}.javaClass.getResourceAsStream("/templates/$name")) {
        "Missing generator template $name"
    }.bufferedReader().use { it.readText() }
    return "// DO NOT EDIT — generated by tools/linalg-generator\n" +
        "// generator-version: 1\n" +
        "// model-version: field-f32-v1\n" + "package ${packages.linalg}\n\n" + source
}

private fun parseArguments(arguments: Array<String>): Arguments {
    var output: Path? = null
    var docsOutput: Path? = null
    var check = false
    var packages: Path? = null
    var index = 0
    while (index < arguments.size) {
        when (val argument = arguments[index]) {
            "--output" -> {
                require(index + 1 < arguments.size) { "--output requires a path" }
                output = Path.of(arguments[++index]).toAbsolutePath().normalize()
            }
            "--docs-output" -> {
                require(index + 1 < arguments.size) { "--docs-output requires a path" }
                docsOutput = Path.of(arguments[++index]).toAbsolutePath().normalize()
            }
            "--check" -> check = true
            "--packages" -> {
                require(index + 1 < arguments.size) { "--packages requires a configuration path" }
                packages = Path.of(arguments[++index]).toAbsolutePath().normalize()
            }
            else -> error("Unknown argument: $argument")
        }
        index++
    }
    return Arguments(
        requireNotNull(output) { "--output is required" },
        requireNotNull(docsOutput) { "--docs-output is required" },
        check,
        packages,
    )
}
