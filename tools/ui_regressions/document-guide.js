const delay = ms => new Promise(resolve => setTimeout(resolve,ms));
const get = id => document.getElementById(id);
const check = (value,message) => {if(!value)throw new Error(message);};
const wait = async (fn,label,timeout=12000) => {
    const until=Date.now()+timeout;
    while(Date.now()<until){if(fn())return;await delay(50);}
    throw new Error(`${label}: ${get('guide-status')?.textContent}; picker query=${document.querySelector('.afield-palette-input')?.value}; picker=${document.querySelector('.afield-palette-list')?.textContent}`);
};
const {sendWithReply} = await import('./afield.mjs');
let seq=0;
const request = payload => new Promise(resolve=>sendWithReply('document-guide',payload,`guide-test-${Date.now()}-${seq++}`,(_,r)=>{resolve({ok:true,...r});return 'remove';}));
try {
    window.openFieldCommandPalette({includeEditor:false,editor:window.globalEditor,query:'Show Document Guide'});
    await wait(()=>document.querySelector('.afield-palette-row')?.textContent.includes('Show Document Guide'),'command is discoverable');
    document.querySelector('.afield-palette-input').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true}));
    await wait(()=>get('document-guide')?.dataset.path==='README.md','reader opens');
    const panel=get('document-guide');
    const openFromAnywhere = async (query, label, path) => {
        get('guide-close').click();
        window.openAnywherePalette();
        const input=document.querySelector('.afield-palette-input');
        await wait(()=>document.activeElement===input,'Open Anything has keyboard focus');
        input.value=query; input.dispatchEvent(new Event('input',{bubbles:true}));
        await wait(()=>[...document.querySelectorAll('.afield-palette-row')].some(r=>r.querySelector('.afield-palette-label')?.textContent===label),`Open Anything finds ${query}`);
        check(document.querySelector('.afield-palette-row.is-active .afield-palette-label')?.textContent===label,`exact guide match should be first: ${query}; got ${document.querySelector('.afield-palette-row.is-active')?.textContent}`);
        input.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true}));
        await wait(()=>!panel.hidden&&panel.dataset.path===path,`Open Anything opens ${path}`);
    };
    await openFromAnywhere('document viewer','Document Viewer','README.md');
    await openFromAnywhere('Movement details','Movement details','docs/Details.md');
    await openFromAnywhere('README.md','A document with a guide','README.md');
    const files=[...get('guide-files').querySelectorAll('button')].map(b=>b.dataset.path);
    check(files.includes('README.md')&&files.includes('docs/Details.md'),'guide discovery missing files');
    check(!files.includes('AGENTS.md')&&!files.some(f=>f.endsWith('_notes_.md')),'non-guide files leaked into catalogue');
    check(getComputedStyle(panel.querySelector('header')).userSelect==='none','selectable interface chrome');
    check(get('guide-close').textContent==='×','standard close icon');
    check(panel.querySelectorAll('.guide-resize').length===4,'resize corners');
    const r=panel.getBoundingClientRect();
    window.interact(panel).fire({type:'resizemove',target:panel,rect:{width:r.width+50,height:r.height-50},deltaRect:{left:0,top:10}});
    check(panel.getBoundingClientRect().height<r.height-30,'resize changes geometry');
    const img=get('guide-reader').querySelector('img');
    await wait(()=>img.complete&&img.naturalWidth>0,'relative asset rendered');
    get('guide-reader').querySelector('a[href^="field://box/"]').click();
    await wait(()=>window.currentSelectedCode?.[0]?.name==='GuideTarget','box link selects target');
    await wait(()=>window.globalEditor?.getPosition?.()?.lineNumber===3,'box link selects line');
    check(!panel.hidden,'guide stays open beside box');
    get('guide-reader').querySelector('a[href^="docs/"]').click();
    await wait(()=>panel.dataset.path==='docs/Details.md','relative guide navigation');
    check([...get('guide-outline').querySelectorAll('button')].some(b=>b.textContent==='Turning'),'heading outline');
    get('guide-back').click();
    await wait(()=>panel.dataset.path==='README.md','back navigation');
    const before=(await request({action:'read',path:'README.md'})).file;
    get('guide-source').click();
    await wait(()=>!get('guide-source-editor').hidden&&get('guide-source-editor').querySelector('.monaco-editor'),'source editor');
    const model=window.globalMonaco.editor.getModels().find(m=>m.getValue()===before.contents);
    check(model,'Markdown Monaco model');
    model.setValue(before.contents+'\n\n## A saved edit\n\nEdited in the guide.');
    get('guide-save').click();
    await wait(()=>get('guide-status').textContent==='Saved to disk','save');
    const saved=(await request({action:'read',path:'README.md'})).file;
    check(saved.contents.includes('A saved edit'),'save reached real file');
    model.setValue(saved.contents+'\n\nMY UNSAVED DRAFT');
    const external=await request({action:'save',path:'README.md',revision:saved.revision,contents:saved.contents+'\n\nEXTERNAL EDIT'});
    check(external.ok,'second writer succeeds');
    await wait(()=>!get('guide-conflict').hidden,'external write flagged');
    check(model.getValue().includes('MY UNSAVED DRAFT'),'draft survives refresh');
    get('guide-save').click();
    await wait(()=>get('guide-status').textContent.includes('file changed on disk'),'stale save refused');
    check((await request({action:'read',path:'README.md'})).file.contents.includes('EXTERNAL EDIT'),'stale save did not overwrite disk');
    get('guide-close').click();check(panel.hidden,'close');
    await window.showDocumentGuide();get('guide-source').click();
    check(model.getValue().includes('MY UNSAVED DRAFT'),'draft survives close/reopen');
    const originalConfirm=window.confirm;window.confirm=()=>true;
    try {get('guide-reload').click();await wait(()=>get('guide-conflict').hidden,'explicit reload');} finally {window.confirm=originalConfirm;}
    check(model.getValue().includes('EXTERNAL EDIT')&&!model.getValue().includes('MY UNSAVED DRAFT'),'reload replaces draft explicitly');
    get('guide-read').click();
    const baseline=(await request({action:'read',path:'README.md'})).file;
    await request({action:'save',path:'README.md',revision:baseline.revision,contents:baseline.contents+'\n\n## Live refresh\n\nSeen without reopening.'});
    await wait(()=>get('guide-reader').textContent.includes('Live refresh'),'clean reader follows disk');
    get('guide-pin').click();
    await wait(()=>window.currentSelectedProperty==='contents','file proxy opened');
    await wait(()=>window.isNotesMarkdownPreviewActive?.(),'file proxy shares Markdown preview');
    const uid=window.currentSelectedCode[0].uid;
    const again=await request({action:'pin',path:'README.md'});
    check(again.uid===uid,'placing again reuses the same proxy');
    // Leave the guide and the code both visible in the retained screenshot.
    await window.showDocumentGuide('docs/Details.md');
    get('guide-reader').querySelector('a[href^="field://box/"]').click();
    return {ok:true,files,proxyUid:uid,sourceLine:window.globalEditor.getPosition().lineNumber};
} catch(error) { return {ok:false,reason:String(error),status:get('guide-status')?.textContent}; }
