const delay=ms=>new Promise(r=>setTimeout(r,ms));
const wait=async(fn,message)=>{for(let i=0;i<160;i++){if(fn())return;await delay(50);}throw Error(message);};
window.setAutoDisplayEditor(false);
window.moveCanvasCamera(0,0,1);
for(const b of [...window.selectedList])window.deselectBox(b);
const frame=[...document.querySelectorAll('.text-frame-box')].find(b=>b.name==='Research notes');
const menu=[...document.querySelectorAll('.box')].find(b=>b.name==='Draft');
if(!frame||!menu)throw Error('Docs fixture missing');
menu.dataset.docsMenu='true';window.__frameContent={frame,menu};
await wait(()=>frame.querySelector('img')?.complete&&frame.querySelector('img')?.naturalWidth>0,'FileManager image did not load: '+JSON.stringify({src:frame.querySelector('img')?.src,document:window.currentDocumentFilename,session:window.currentDocumentSessionKey}));
await wait(()=>[...document.querySelectorAll('.text-frame-overflow')].every(e=>e.hidden),'Documentation frames unexpectedly clip their contents');
const image=frame.querySelector('img'),url=new URL(image.src);
if(url.pathname!=='/api/text-frame-asset'||url.searchParams.get('path')!=='%document/frame-diagram.svg')throw Error('Wrong FileManager URL');
const good=await fetch(url);
if(!good.ok||!good.headers.get('content-type')?.includes('svg')||!good.headers.get('content-security-policy')?.includes('sandbox'))throw Error('Local image response incorrect');
url.searchParams.set('path','%document/not-authored.svg');
if((await fetch(url)).status!==404)throw Error('Unauthored image reference was accepted');
url.searchParams.set('path','%document/frame-diagram.svg');url.searchParams.set('box',menu.uid);
if((await fetch(url)).status!==404)throw Error('Ordinary box accepted image capability');
return {ok:true,imageLoaded:true,localFileManager:true,unreferencedFilesRefused:true};
