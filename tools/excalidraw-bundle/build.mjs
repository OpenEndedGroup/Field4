// Builds Field's vendored Excalidraw drawing layer.
//
//   cd tools/excalidraw-bundle && npm ci && npm run build
//
// Output goes to src/jsMain/resources/excalidraw/, which Field serves at /excalidraw/ (the
// `staticFiles(dir = src/jsMain/resources/)` mount in Server.kt). The output is committed, like
// Monaco, so neither a Field build nor an offline machine needs npm.
import { build } from "esbuild";
import { cpSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../src/jsMain/resources/excalidraw");
const pkgDist = join(here, "node_modules/@excalidraw/excalidraw/dist/prod");

// Xiaolai is Excalidraw's CJK hand-drawn font: 12 MB of subsets, fetched from Excalidraw's CDN
// when a CJK glyph is first drawn. Everything else (~0.5 MB) is served locally so the Latin
// fonts work offline.
const SKIPPED_FONTS = new Set(["Xiaolai"]);

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

await build({
    entryPoints: { "field-excalidraw": join(here, "entry.jsx") },
    outdir: out,
    bundle: true,
    splitting: true,
    format: "esm",
    minify: true,
    target: "es2020",
    jsx: "automatic",
    conditions: ["production"],
    define: { "process.env.NODE_ENV": '"production"', "process.env.IS_PREACT": '"false"' },
    loader: { ".woff2": "file", ".ttf": "file", ".png": "file", ".svg": "file" },
    chunkNames: "chunks/[name]-[hash]",
    assetNames: "assets/[name]-[hash]",
    legalComments: "linked",
    logLevel: "info",
});

for (const family of readdirSync(join(pkgDist, "fonts"))) {
    if (SKIPPED_FONTS.has(family)) continue;
    cpSync(join(pkgDist, "fonts", family), join(out, "fonts", family), { recursive: true });
}

writeFileSync(
    join(out, "README.md"),
    "Generated by `tools/excalidraw-bundle` (`npm ci && npm run build`). Do not edit by hand.\n" +
        "Excalidraw is MIT-licensed; see the `.LEGAL.txt` files beside the bundles.\n"
);
