plugins {
    kotlin("jvm")
    id("me.champeau.jmh") version "0.7.2"
}

repositories {
    mavenCentral()
}

// OpenCV is a benchmark-only baseline, exactly as JOML is for :tools:linalg-bench. It happens to
// already be a Field runtime dependency (via JavaCV, for video), but the imaging family does NOT
// use it and must not start to — the whole point of the family is that it is dependency-free. It is
// here to answer one question honestly: "is the pure-Kotlin path fast enough to use instead?"
val opencvVersion = "4.9.0-1.5.10"
val openblasVersion = "0.3.26-1.5.10"
val javacppVersion = "1.5.10"
val bytedecoPlatform = when {
    System.getProperty("os.name").startsWith("Mac") ->
        if (System.getProperty("os.arch") == "aarch64") "macosx-arm64" else "macosx-x86_64"
    System.getProperty("os.name").startsWith("Windows") -> "windows-x86_64"
    else -> if (System.getProperty("os.arch") == "aarch64") "linux-arm64" else "linux-x86_64"
}

dependencies {
    "jmhImplementation"("org.bytedeco:javacpp:$javacppVersion")
    "jmhImplementation"("org.bytedeco:javacpp:$javacppVersion:$bytedecoPlatform")
    "jmhImplementation"("org.bytedeco:opencv:$opencvVersion")
    "jmhImplementation"("org.bytedeco:opencv:$opencvVersion:$bytedecoPlatform")
    // opencv's native library links against openblas; without these classifiers every forked JVM
    // dies in @Setup with UnsatisfiedLinkError("no jniopenblas_nolapack") and JMH still reports
    // BUILD SUCCESSFUL with an empty results table. Mirrors the root build's dependency block.
    "jmhImplementation"("org.bytedeco:openblas:$openblasVersion")
    "jmhImplementation"("org.bytedeco:openblas:$openblasVersion:$bytedecoPlatform")
}

// The value type and the filter layer are dependency-free apart from two trivial declarations
// (`afield.ToHTML` and `afield.CompletionCategory`), so the benchmark compiles the real sources
// directly rather than dragging in the whole afield runtime — the same approach
// :tools:linalg-bench takes. These are the SAME FILES the app ships; there is no second copy of the
// algorithms to drift out of sync.
//
// `imaging_features.kt` and `imaging_geometry.kt` are deliberately NOT copied: they reference the
// generated linalg types (`Vec2`) and the FLine layer, which would pull in the runtime. Benchmark
// those through the app build if they ever need it — the convolution path, which is what
// everything else is built on, does not.
val assembleImagingSources = tasks.register<Copy>("assembleImagingSources") {
    val root = rootProject.layout.projectDirectory
    into(layout.buildDirectory.dir("imaging-sources"))
    from(root.dir("src/jvmMain/kotlin")) {
        include("afield/stdlib/imaging.kt")
        include("afield/stdlib/imaging_filters.kt")
        include("afield/stdlib/imaging_simd.kt")
        include("afield/util/PngEncoder.kt")
    }
}

// `afield.ToHTML` lives in ValueVisualizer.kt and `afield.CompletionCategory` in util.kt, both of
// which drag in the rest of the runtime. Img only needs the two declarations themselves.
val generateImagingBenchStubs = tasks.register("generateImagingBenchStubs") {
    val out = layout.buildDirectory.dir("imaging-stubs/afield")
    outputs.dir(layout.buildDirectory.dir("imaging-stubs"))
    doLast {
        val f = out.get().file("BenchStubs.kt").asFile
        f.parentFile.mkdirs()
        f.writeText(
            """
            // Generated by generateImagingBenchStubs. Do not edit.
            //
            // Minimal stand-ins for the two afield declarations the imaging sources reference. Kept
            // identical in shape to the originals (afield/visualization/ValueVisualizer.kt and
            // afield/util.kt) so the real sources compile unmodified.
            package afield

            interface ToHTML {
                fun toHTML(): String
            }

            @Retention(AnnotationRetention.RUNTIME)
            @Target(AnnotationTarget.FILE, AnnotationTarget.CLASS, AnnotationTarget.FUNCTION, AnnotationTarget.PROPERTY)
            annotation class CompletionCategory(val value: String)
            """.trimIndent() + "\n"
        )
    }
}

// Must be the SAME JVM the app runs on (root build.gradle.kts pins GRAAL_VM), or the numbers
// describe a JVM nobody ships. It also matters mechanically: -XX:+EnableJVMCI is a supported option
// on GraalVM but an *experimental* one everywhere else, so a plain `jvmToolchain(25)` silently
// resolves to Adoptium and every forked JMH JVM dies with "must be enabled via
// -XX:+UnlockExperimentalVMOptions" and reports zero benchmarks — a green build with no results.
java {
    toolchain {
        languageVersion.set(JavaLanguageVersion.of(25))
        vendor.set(JvmVendorSpec.GRAAL_VM)
    }
}

kotlin {
    sourceSets.named("main") {
        kotlin.srcDir(assembleImagingSources)
        kotlin.srcDir(generateImagingBenchStubs)
    }
}

jmh {
    warmupIterations.set(3)
    warmup.set("1s")
    iterations.set(5)
    timeOnIteration.set("1s")
    fork.set(2)
    benchmarkMode.set(listOf("avgt"))
    timeUnit.set("ms")
    resultFormat.set("TEXT")
    // Same opt-in as the main build's runJvm/test tasks. On the GraalVM toolchain C2 must be forced
    // as the host JIT (-XX:-UseJVMCICompiler, JVMCI still enabled for Truffle) or neither the Vector
    // API nor C2 scalar autovectorization engages and the numbers mean nothing — see the
    // vectorizationJvmArgs note in the root build.gradle.kts.
    jvmArgsAppend.set(
        listOf(
            "--add-modules", "jdk.incubator.vector",
            "-XX:+EnableJVMCI",
            "-XX:-UseJVMCICompiler",
            // JavaCV/OpenCV reaches into JDK internals on 25.
            "--enable-native-access=ALL-UNNAMED",
        )
    )
}
