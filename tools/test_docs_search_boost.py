#!/usr/bin/env python3
"""Pin `docs_search_boost`: written docs pages outrank generated reference pages in site search.

The patch rewrites exact strings in Zensical's minified search worker, so the test that matters
is the one against the worker Zensical actually ships. It needs Zensical installed (the `docs`
group) and skips without it; the ranking test also needs `node`, and runs the real worker on a
small index, so it checks the order a reader sees rather than the substitution.
"""

from __future__ import annotations

import importlib.util
import json
import shutil
import subprocess
import tempfile
import textwrap
import unittest
from pathlib import Path

from docs_search_boost import (WORKER_DIR, WRITTEN_PAGE_BOOST, WorkerPatchError, apply,
                               boost_search_index, generated_page_locations, page_location,
                               patch_worker_source)

REPO_ROOT = Path(__file__).resolve().parent.parent


def zensical_worker() -> Path | None:
    """The search worker of the Zensical the docs build uses, if it is installed."""
    roots = []
    spec = importlib.util.find_spec("zensical")
    if spec is not None and spec.origin:
        roots.append(Path(spec.origin).parent)
    roots += sorted(REPO_ROOT.glob(".venv/lib/python*/site-packages/zensical"))
    for root in roots:
        workers = sorted((root / "templates" / WORKER_DIR).glob("search.*.min.js"))
        if workers:
            return workers[0]
    return None


# Loads a worker the way the site's bundle does and prints the locations of a query's hits in
# order. Messages are cloned, as `postMessage` would: the worker mutates the query it is given.
RANK_JS = textwrap.dedent("""
    const fs = require("fs"), vm = require("vm");
    const [worker, index, query] = process.argv.slice(2);
    const data = JSON.parse(fs.readFileSync(index, "utf8"));
    let result = null, ready;
    const loaded = new Promise(r => ready = r);
    const self = { postMessage(m) { if (m.type === 1) ready(); if (m.type === 3) result = m.data; } };
    vm.runInNewContext(fs.readFileSync(worker, "utf8"), { self, console, Map, Set, Date, Math, Promise });
    (async () => {
      self.onmessage({ data: structuredClone({ type: 0, data }) });
      await loaded;
      const filter = { input: { type: "operator", data: { operator: "and", operands: [] } },
                       aggregation: { input: [{ type: "term", data: { field: "tags" } }] } };
      self.onmessage({ data: structuredClone({ type: 2, data: { input: query, filter } }) });
      console.log(JSON.stringify(result.items.map(it => data.items[it.id].location)));
    })();
""")


def item(location: str, title: str, text: str = "") -> dict:
    page = location.split("#", 1)[0].rstrip("/") or "Home"
    return {"location": location, "level": 2, "title": title, "text": text, "path": [page], "tags": []}


class PageLocationTest(unittest.TestCase):
    def test_matches_use_directory_urls(self) -> None:
        self.assertEqual(page_location(Path("index.md")), "")
        self.assertEqual(page_location(Path("sound.md")), "sound/")
        self.assertEqual(page_location(Path("reference/index.md")), "reference/")
        self.assertEqual(page_location(Path("reference/source/jvmMain/afield/X.md")),
                         "reference/source/jvmMain/afield/X/")
        self.assertEqual(page_location(Path("guides/README.md")), "guides/")


class GeneratedPagesTest(unittest.TestCase):
    def test_first_line_marker_decides(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            docs = Path(tmp)
            (docs / "reference").mkdir()
            (docs / "sound.md").write_text("# Sound\n\n<!-- generated by nothing; a comment -->\n")
            (docs / "linear_algebra_api.md").write_text("<!-- Generated by tools/x.py. Do not edit. -->\n# API\n")
            (docs / "reference" / "index.md").write_text("<!-- generated by tools/y.py -->\n# Ref\n")
            self.assertEqual(generated_page_locations(docs), {"linear_algebra_api/", "reference/"})

    def test_the_built_reference_is_generated(self) -> None:
        docs = REPO_ROOT / "public" / ".zensical-generated" / "docs"
        if not (docs / "reference" / "index.md").is_file():
            self.skipTest("no generated docs tree; run tools/build_zensical_docs.py")
        generated = generated_page_locations(docs)
        self.assertIn("reference/", generated)
        self.assertNotIn("sound/", generated)
        self.assertNotIn("", generated)


class BoostIndexTest(unittest.TestCase):
    def test_boosts_written_pages_only(self) -> None:
        index = {"items": [item("sound/", "Sound"), item("sound/#notes", "Notes"),
                           item("reference/", "Reference"), item("reference/#x", "X")]}
        self.assertEqual(boost_search_index(index, frozenset({"reference/"})), 2)
        self.assertEqual([i.get("boost") for i in index["items"]],
                         [WRITTEN_PAGE_BOOST, WRITTEN_PAGE_BOOST, None, None])

    def test_refuses_a_worker_it_does_not_recognise(self) -> None:
        with self.assertRaises(WorkerPatchError):
            patch_worker_source("self.onmessage=()=>{}")


class ZensicalWorkerTest(unittest.TestCase):
    def setUp(self) -> None:
        worker = zensical_worker()
        if worker is None:
            self.skipTest("Zensical is not installed (uv run --project . --group docs ...)")
        self.worker = worker

    def test_patches_the_shipped_worker(self) -> None:
        patched = patch_worker_source(self.worker.read_text(encoding="utf-8"))
        self.assertIn("self.__fieldBoost", patched)

    def test_apply_renames_the_worker_and_repoints_pages(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            site, docs = Path(tmp) / "site", Path(tmp) / "docs"
            (site / WORKER_DIR).mkdir(parents=True)
            docs.mkdir()
            shutil.copy(self.worker, site / WORKER_DIR / self.worker.name)
            (docs / "sound.md").write_text("# Sound\n")
            (site / "search.json").write_text(json.dumps({"config": {}, "items": [item("sound/", "Sound")]}))
            config = f'{{"search":"./{WORKER_DIR.as_posix()}/{self.worker.name}"}}'
            (site / "index.html").write_text(f'<script id="__config">{config}</script>')
            report = apply(site_dir=site, docs_dir=docs)
            self.assertNotEqual(report.worker, self.worker.name)
            self.assertEqual([p.name for p in (site / WORKER_DIR).iterdir()], [report.worker])
            self.assertIn(report.worker, (site / "index.html").read_text())
            self.assertEqual(report.pages_repointed, 1)
            self.assertEqual(json.loads((site / "search.json").read_text())["items"][0]["boost"],
                             WRITTEN_PAGE_BOOST)

    def test_written_pages_rank_above_generated_ones(self) -> None:
        node = shutil.which("node")
        if node is None:
            self.skipTest("node is not installed")
        items = [
            # Index order puts the generated hits first, so only the boost can lift the others.
            item("reference/#slidertest", "SliderTest", "a test of the slider"),
            item("reference/#sliderconfig", "SliderConfig", "the config for a slider"),
            # The word at the same position as in SliderTest's text: an earlier one would win alone.
            item("visualizers/#sliders", "Sliders", "you can drag the slider"),
            item("tour/#controls", "Controls", "a slider is the simplest control"),
        ]
        generated = frozenset({"reference/"})

        def ranked(patch: bool) -> list[str]:
            with tempfile.TemporaryDirectory() as tmp:
                # Zensical's own separator, as it writes it into `search.json`.
                index = {"config": {"separator": r'[\s\-_,:!=\[\]()\\"`/]+|\.(?!\d)'},
                         "items": json.loads(json.dumps(items))}
                worker_source = self.worker.read_text(encoding="utf-8")
                if patch:
                    boost_search_index(index, generated)
                    worker_source = patch_worker_source(worker_source)
                (Path(tmp) / "search.json").write_text(json.dumps(index))
                (Path(tmp) / "worker.js").write_text(worker_source)
                (Path(tmp) / "rank.js").write_text(RANK_JS)
                out = subprocess.run([node, "rank.js", "worker.js", "search.json", "slider"], cwd=tmp,
                                     capture_output=True, text=True, check=False, timeout=60)
                # The tail: a worker error echoes the whole minified source first.
                self.assertEqual(out.returncode, 0, out.stderr[-1500:])
                return json.loads(out.stdout)

        self.assertEqual(ranked(patch=False)[0], "reference/#slidertest")
        # A written title beats a generated title; a generated title still beats a written page
        # that only mentions the word in its text.
        self.assertEqual(ranked(patch=True), ["visualizers/#sliders", "reference/#slidertest",
                                              "reference/#sliderconfig", "tour/#controls"])


if __name__ == "__main__":
    unittest.main()
