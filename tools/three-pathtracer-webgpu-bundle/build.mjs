// Builds the three viewer's WebGPU path tracer.
//
//   cd tools/three-pathtracer-webgpu-bundle && npm ci && npm run build
//
// three-gpu-pathtracer ships its WebGPU tracer only as source (about 40 imports from
// three-mesh-bvh/webgpu and three/tsl), so it is bundled here, with oidn-webgpu, into one module.
// three is left out: the bundle imports the vendored three.webgpu.js / three.tsl.js, which share
// three.core.js with the viewer's WebGL three.module.js, so the WebGPU tracer reads the very
// scene objects the viewer built. Those two files are copied beside three.core.js, and the build
// fails unless the npm three.core.js is byte-identical to the vendored one.
//
// The OIDN denoiser weights are not in the npm package; they are fetched from oidn-webgpu's tag
// and checked against pinned checksums. Everything written is committed, like Monaco, so neither
// a Field build nor an offline machine needs npm or the network.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const modules = join(here, 'node_modules');
const vendor = join(here, '../../src/commonMain/resources/vendor');
const pkg = name => JSON.parse(readFileSync(join(modules, name, 'package.json'), 'utf8')).version;

const THREE = pkg('three'), TRACER = pkg('three-gpu-pathtracer'), OIDN = pkg('oidn-webgpu');
const threeDir = join(vendor, 'three', THREE);
const out = join(vendor, 'three-gpu-pathtracer', TRACER, 'webgpu');
const weightsDir = join(vendor, 'oidn-webgpu', OIDN);
const threeUrl = `/vendor/three/${THREE}/`;

// The guided HDR model: the tracer accumulates albedo and normal buffers and its output is HDR.
const WEIGHTS = {
    tag: `v${OIDN}`,
    files: {
        'rt_hdr_alb_nrm.tza': 'e586ef2ff48d7fbb7611986405220ed8fc5c13ca79bfc40be4dc742fbf959e1a',
        'LICENSE.txt': 'cfc7749b96f63bd31c3c42b5c471bf756814053e847c10f3eb003417bc523d30',
    },
};

const npmCore = readFileSync(join(modules, 'three/build/three.core.js'));
const vendoredCore = readFileSync(join(threeDir, 'three.core.js'));
if (!npmCore.equals(vendoredCore)) throw new Error(`npm three ${THREE} three.core.js differs from ${threeDir}/three.core.js`);
for (const file of ['three.webgpu.js', 'three.tsl.js']) copyFileSync(join(modules, 'three/build', file), join(threeDir, file));

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const external = { 'three': 'three.webgpu.js', 'three/webgpu': 'three.webgpu.js', 'three/tsl': 'three.tsl.js' };
await build({
    entryPoints: [join(here, 'entry.js')],
    outfile: join(out, 'index.module.js'),
    bundle: true,
    format: 'esm',
    minify: true,
    target: 'es2022',
    legalComments: 'none',
    logLevel: 'info',
    plugins: [{
        name: 'vendored-three',
        setup(b) { b.onResolve({ filter: /^three(\/webgpu|\/tsl)?$/ }, a => ({ path: threeUrl + external[a.path], external: true })); },
    }],
});
const licenses = ['three-gpu-pathtracer', 'three-mesh-bvh', 'oidn-webgpu'].map(name =>
    `## ${name} ${pkg(name)}\n\n${readFileSync(join(modules, name, 'LICENSE'), 'utf8').trim()}\n`);
writeFileSync(join(out, 'LICENSES.md'), `# Bundled into index.module.js\n\n${licenses.join('\n')}`);
writeFileSync(join(out, 'README.md'),
    'Generated by `tools/three-pathtracer-webgpu-bundle` (`npm ci && npm run build`). Do not edit by hand.\n');

mkdirSync(weightsDir, { recursive: true });
for (const [file, sha] of Object.entries(WEIGHTS.files)) {
    const url = `https://raw.githubusercontent.com/pissang/oidn-webgpu/${WEIGHTS.tag}/weights/${file}`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: ${response.status}`);
    const bytes = Buffer.from(await response.arrayBuffer());
    const got = createHash('sha256').update(bytes).digest('hex');
    if (got !== sha) throw new Error(`${file}: sha256 ${got}, expected ${sha}`);
    writeFileSync(join(weightsDir, file), bytes);
}
writeFileSync(join(weightsDir, 'README.md'),
    `Open Image Denoise weights (Apache 2.0, LICENSE.txt) from oidn-webgpu ${WEIGHTS.tag}, fetched and checksummed by\n` +
    '`tools/three-pathtracer-webgpu-bundle`. Do not edit by hand.\n');
