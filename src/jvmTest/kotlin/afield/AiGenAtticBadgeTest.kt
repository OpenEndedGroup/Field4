package afield

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * The "🤖 ai-generated — view in attic" badge, restored on the string-parsed path.
 *
 * `ai("…")` hides the body it generates: the call site becomes `return __name(…)` and the code lives
 * in the box's attic. The badge is the only thing that says so, and it was unreachable from
 * `ba36f5b30` (2026-04-11), which took the `DeclarationDescriptor` it was gated on away, until this.
 */
class AiGenAtticBadgeTest {

    private fun boxWithAttic(id: String, attic: String): Box =
        Box(id).also { it.attic = attic }

    private fun atticFor(name: String) = """
        // @ai-gen: $name | sig: (a: Double): FLine | prompt: a random wiggly FLine
        fun $name(a: Double): FLine { return FLine() }
        // @ai-gen-end: $name
    """.trimIndent()

    @Test
    fun `a function generated by ai is badged`() {
        val box = boxWithAttic("badge-hit", atticFor("__wiggle"))
        val html = aiGeneratedAtticBadge(box, "wiggle")
        assertTrue("ai-generated" in html, html)
        assertTrue("view in attic" in html, html)
    }

    /** The badge is a link: it switches the box to its attic property. */
    @Test
    fun `the badge links to this box's attic`() {
        val box = boxWithAttic("badge-link", atticFor("__wiggle"))
        val html = aiGeneratedAtticBadge(box, "wiggle")
        assertTrue("switchToProperty('badge-link','attic')" in html, html)
    }

    @Test
    fun `a hand-written function is not badged`() {
        assertEquals("", aiGeneratedAtticBadge(boxWithAttic("plain", atticFor("__wiggle")), "somethingElse"))
    }

    @Test
    fun `a box with no attic is not badged`() {
        assertEquals("", aiGeneratedAtticBadge(Box("no-attic"), "wiggle"))
    }

    /**
     * The bug in the original: it tested `attic.contains("// @ai-gen: __wiggle")`, and
     * `"// @ai-gen: __wiggleMore | sig: …"` contains exactly that. Going through the macro's own
     * [afield.macros.parseAtticBlock] matches the whole name.
     */
    @Test
    fun `a longer generated name does not badge the shorter one`() {
        val box = boxWithAttic("prefix", atticFor("__wiggleMore"))
        assertEquals("", aiGeneratedAtticBadge(box, "wiggle"))
    }

    @Test
    fun `the implementation name itself is badged`() {
        val box = boxWithAttic("impl", atticFor("__wiggle"))
        assertTrue("ai-generated" in aiGeneratedAtticBadge(box, "__wiggle"))
    }

    /** Completion hands over names with call and generic syntax still attached. */
    @Test
    fun `a name arriving with call syntax still matches`() {
        val box = boxWithAttic("call-syntax", atticFor("__wiggle"))
        assertTrue("ai-generated" in aiGeneratedAtticBadge(box, "wiggle("), "call")
        assertTrue("ai-generated" in aiGeneratedAtticBadge(box, "wiggle<Double>"), "generic")
    }
}
