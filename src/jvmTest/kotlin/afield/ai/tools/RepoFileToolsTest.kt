package afield.ai.tools

import java.nio.file.Files
import java.nio.file.Path
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class RepoFileToolsTest {
    private class Fixture(read: List<String> = listOf("**"), write: List<String> = listOf("docs/page.md", "new/**")) : AutoCloseable {
        val outer: Path = Files.createTempDirectory("field-repo-tools")
        val root: Path = Files.createDirectories(outer.resolve("repo"))
        init {
            file("docs/page.md", "one\ntwo needle\nthree\n")
            file("docs/other.md", "needle elsewhere\n")
            file("src/A.kt", "fun a() = 1\n")
            file(".git/config", "needle in git\n")
            Files.writeString(outer.resolve("secret.txt"), "needle secret\n")
        }
        val tools = RepoFileTools(RepoScope(root, read, write))
        fun file(path: String, text: String): Path = root.resolve(path).also { Files.createDirectories(it.parent); Files.writeString(it, text) }
        override fun close() { outer.toFile().deleteRecursively() }
    }

    @Test fun readsRangesWithLineNumbers() = Fixture().use { f ->
        val r = f.tools.read(RepoReadFileRequest("docs/page.md", 2, 3))
        assertTrue(r.success, r.message)
        assertEquals("2\ttwo needle\n3\tthree", r.text)
        assertEquals(3, r.totalLines)
    }

    @Test fun refusesTraversalAbsoluteGitAndUnlistedPaths() = Fixture(read = listOf("docs/**")).use { f ->
        for (bad in listOf("../secret.txt", "docs/../../secret.txt", f.outer.resolve("secret.txt").toString(), ".git/config",
                "src/A.kt", "docs\\page.md", "", "./docs/./page.md")) {
            val r = f.tools.read(RepoReadFileRequest(bad))
            assertFalse(r.success, "'$bad' should be refused")
        }
        assertTrue(f.tools.read(RepoReadFileRequest("docs/page.md")).success)
    }

    @Test fun refusesSymlinkEscapes() = Fixture().use { f ->
        Files.createSymbolicLink(f.root.resolve("link.txt"), f.outer.resolve("secret.txt"))
        Files.createSymbolicLink(f.root.resolve("linkdir"), f.outer)
        assertFalse(f.tools.read(RepoReadFileRequest("link.txt")).success)
        assertFalse(f.tools.read(RepoReadFileRequest("linkdir/secret.txt")).success)
        assertFalse(f.tools.write(RepoWriteFileRequest("new/../linkdir/x.txt", "x")).success)
        val hits = f.tools.search(RepoSearchRequest("needle")).matches.map { it.path }.toSet()
        assertEquals(setOf("docs/page.md", "docs/other.md"), hits, "no match through a link, in .git, or outside the root")
    }

    @Test fun writesOnlyTheWritableList() = Fixture().use { f ->
        assertFalse(f.tools.patch(RepoPatchFileRequest("docs/other.md", "needle", "pin")).success)
        assertFalse(f.tools.write(RepoWriteFileRequest("src/B.kt", "x")).success)
        assertFalse(f.tools.write(RepoWriteFileRequest(".git/hooks/pre-commit", "x")).success)
        assertTrue(f.tools.write(RepoWriteFileRequest("new/dir/B.kt", "fun b() = 2\n")).success)
        assertFalse(f.tools.write(RepoWriteFileRequest("new/dir/B.kt", "again")).success, "no silent overwrite")
        assertEquals("fun b() = 2\n", Files.readString(f.root.resolve("new/dir/B.kt")))
        assertEquals(listOf("new/dir/B.kt"), f.tools.written)
    }

    @Test fun refusesToEditAGeneratedFile() = Fixture().use { f ->
        f.file("docs/page.md", "// DO NOT EDIT — generated by tools/gen\nfun a() = 1\n")
        val r = f.tools.patch(RepoPatchFileRequest("docs/page.md", "fun a", "fun b"))
        assertFalse(r.success)
        assertTrue("tools/gen" in r.message, r.message)
        assertFalse(f.tools.write(RepoWriteFileRequest("docs/page.md", "x", overwrite = true)).success)
    }

    @Test fun patchNeedsOneExactOccurrence() = Fixture().use { f ->
        f.file("docs/page.md", "a x a\n")
        assertFalse(f.tools.patch(RepoPatchFileRequest("docs/page.md", "a", "b")).success, "two occurrences")
        assertFalse(f.tools.patch(RepoPatchFileRequest("docs/page.md", "zzz", "b")).success, "none")
        assertTrue(f.tools.patch(RepoPatchFileRequest("docs/page.md", "x", "y")).success)
        assertTrue(f.tools.patch(RepoPatchFileRequest("docs/page.md", "a", "b", replaceAll = true)).success)
        assertEquals("b y b\n", Files.readString(f.root.resolve("docs/page.md")))
    }

    @Test fun listAndRegexSearchStayInsideTheReadableList() = Fixture(read = listOf("docs/*.md")).use { f ->
        assertEquals(listOf("docs/other.md", "docs/page.md"), f.tools.list(RepoListFilesRequest()).files)
        val r = f.tools.search(RepoSearchRequest("^two\\s", regex = true))
        assertEquals(listOf(RepoMatch("docs/page.md", 2, "two needle")), r.matches)
        assertFalse(f.tools.search(RepoSearchRequest("(", regex = true)).success)
    }
}
